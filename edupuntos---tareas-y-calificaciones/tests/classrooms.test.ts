import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { once } from 'node:events';
import { Store } from '../server/store';
import { createUser } from '../server/auth';
import { createApp } from '../server/app';
import { readWorkbook, workbookBuffer } from './workbook-helpers';

test('local classroom permissions protect photos, exports, imports and active sessions after revocation',async t=>{
  const dir=mkdtempSync(path.join(tmpdir(),'edupuntos-classrooms-')),store=new Store(dir);
  const {app,close}=createApp(store,{secureCookies:false});
  const teacherId=createUser(store,'teacher-a','Classroom-test-123','teacher',undefined,['sec-1-a']);
  createUser(store,'teacher-b','Classroom-test-123','teacher',undefined,['sec-2-b']);
  createUser(store,'student-a','Classroom-test-123','student','est-1');
  const data=store.load(); data.students.find(s=>s.id==='est-2')!.classroomId='sec-2-b';
  data.assignments.push({id:'task-b',classroomId:'sec-2-b',title:'Privado 2B',subject:'Ciencia',dueDate:'2026-12-01',description:'',createdAt:'2026-10-14'});
  store.save(data);
  const server=app.listen(0,'127.0.0.1'); await once(server,'listening');
  const base=`http://127.0.0.1:${(server.address() as any).port}`;
  t.after(async()=>{close();server.closeAllConnections();await new Promise<void>(resolve=>server.close(()=>resolve()));store.close();rmSync(dir,{recursive:true,force:true});});
  const call=(role:string,url:string,cookie='',body?:unknown)=>fetch(`${base}/api/${role}${url}`,{method:body?'POST':'GET',headers:{cookie,'Content-Type':'application/json','X-EduPuntos-Client':role},body:body?JSON.stringify(body):undefined});
  const login=async(role:string,username:string)=>{
    const res=await call(role,'/auth/login','',{username,password:'Classroom-test-123'});assert.equal(res.status,200);return res.headers.get('set-cookie')!.split(';')[0];
  };
  const [a,b,student]=await Promise.all([login('teacher','teacher-a'),login('teacher','teacher-b'),login('student','student-a')]);
  assert.equal((await call('teacher','/state?classroom=sec-2-b',a)).status,403);
  assert.equal((await call('student','/state?classroom=sec-2-b',student)).status,403);
  const photo='data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=';
  assert.equal((await call('student','/submissions',student,{assignmentId:'task-b',photoUrl:photo})).status,404);
  const submitted=await call('student','/submissions',student,{assignmentId:'asg-1',photoUrl:photo});assert.equal(submitted.status,200);
  const state=(await submitted.json()).state;
  const file=state.submissions.find((s:any)=>s.assignmentId==='asg-1').photoUrl.replace('/student/','/teacher/');
  assert.equal((await fetch(base+file,{headers:{cookie:a}})).status,200);
  assert.equal((await fetch(base+file,{headers:{cookie:b}})).status,404);
  const sheet=await readWorkbook(new Uint8Array(await (await call('teacher','/excel-export',b)).arrayBuffer()));
  assert.ok(sheet.some(row=>row.includes('EST-02')));
  assert.equal(sheet.some(row=>row.includes('EST-01')),false);
  assert.equal(JSON.stringify(sheet).includes('asg-1'),false);
  const before=store.load();
  const invalid=await workbookBuffer([['CÓDIGO','Tarea [asg-1]'],['EST-01','A']]);
  assert.equal((await call('teacher','/excel-import',b,{fileBase64:invalid.toString('base64')})).status,400);
  assert.deepEqual(store.load(),before);
  assert.equal((await call('teacher','/rewards',b,{firstPlace:'Solo 2B',secondPlace:'Dos',thirdPlace:'Tres'})).status,200);
  assert.notEqual((await (await call('teacher','/state',a)).json()).state.rewards.firstPlace,'Solo 2B');
  store.db.prepare('DELETE FROM teacher_classrooms WHERE user_id=?').run(teacherId);
  assert.equal((await call('teacher','/state',a)).status,403);
  assert.equal((await fetch(base+file,{headers:{cookie:a}})).status,404);
  assert.equal((await call('teacher','/excel-export',a)).status,403);
  assert.throws(()=>createUser(store,'bad-class','Classroom-test-123','teacher',undefined,['sec-1-a','sec-6-a']));
  assert.equal(store.db.prepare("SELECT id FROM users WHERE username='bad-class'").get(),undefined);
});
